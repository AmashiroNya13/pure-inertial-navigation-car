uint32 driver_flash_start_address_get(driver_flash_runtime_t* flash_runtime)
{
    uint64 sector_group = flash_runtime->sector_group;
    uint32 sector_index = 0u;

    while ((sector_group & 1u) == 0u)
    {
        sector_group >>= 1u;
        sector_index++;
    }

    return driver_flash_sector[sector_index]->start_address;
}

uint8 driver_flash_read8(uint32 address)
{
    driver_flash_sector_t* sector = driver_flash_sector_getByAddress(address);

    if (sector == NULL_PTR)
    {
        return 0u;
    }

    if (driver_flash_isAddressValid(sector, address, 1u) == FALSE)
    {
        return 0u;
    }

    return *((const uint8*)address);
}

