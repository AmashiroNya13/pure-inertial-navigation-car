void driver_flash_init(driver_flash_cfg_t* flash_cfg, driver_flash_runtime_t* flash_runtime)
{
    uint64 sector_group = flash_cfg->sector_group;
    uint32 sector_index = 0u;

    flash_runtime->sector_group = flash_cfg->sector_group;
    flash_runtime->sector_full_flag = 0u;
    flash_runtime->group_capacity = 0u;
    flash_runtime->storage_proportion = 0u;
    flash_runtime->offset = 0u;

    while (sector_group != 0u)
    {
        if ((sector_group & 1u) != 0u)
        {
            flash_runtime->group_capacity +=
                driver_flash_sector[sector_index]->end_address - driver_flash_sector[sector_index]->start_address + 1u;
        }

        sector_group >>= 1u;
        sector_index++;
    }
}

boolean driver_flash_autoDFlashGroupWrite(driver_flash_runtime_t* flash_runtime, uint32 word_l, uint32 word_u)
{
    driver_flash_sector_t* sector;
    uint64 available_sector_flag;
    uint32 page_address;
    uint64 sector_group = flash_runtime->sector_group;
    uint32 sector_index = 0u;

    while (TRUE)
    {
        available_sector_flag = sector_group & (~flash_runtime->sector_full_flag);

        if (available_sector_flag == 0u)
        {
            return FALSE;
        }

        sector_index = 0u;
        while (((available_sector_flag >> sector_index) & 1u) == 0u)
        {
            sector_index++;
        }

        sector = driver_flash_sector[sector_index];
        page_address = sector->start_address + flash_runtime->offset;

        if (page_address <= sector->end_address)
        {
            break;
        }

        flash_runtime->sector_full_flag |= (1ULL << sector_index);
        flash_runtime->offset = 0u;
    }

    IfxFlash_enterPageMode(page_address);
    IfxFlash_loadPage(page_address, word_l, word_u);
    driver_flash_safety_endinit_clear();
    IfxFlash_writePage(page_address);
    driver_flash_safety_endinit_set();
    IfxFlash_waitUnbusy(sector->flash_index,
                        sector->flash_type);

    flash_runtime->offset += sector->page_length;
    flash_runtime->storage_proportion += sector->page_length;

    if ((sector->start_address + flash_runtime->offset) > sector->end_address)
    {
        flash_runtime->sector_full_flag |= (1ULL << sector_index);
        flash_runtime->offset = 0u;
    }

    return TRUE;
}

